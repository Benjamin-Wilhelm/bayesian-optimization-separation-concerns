"""Raw experimental data dataclasses for one (experiment, benchmark, seed).

A raw seed JSON contains ONLY trajectory-level experimental information
generated by ``run.py``.  It must contain no aggregate statistics and no
across-seed analysis.

Canonical JSON structure::

    {
      "metadata":        {SeedMetadata fields},
      "initial_design":  {InitialDesign fields},
      "methods": {
        "<method_name>": {
          "train_label":     "y_obs" | "abs(y_obs - target)",
          "trajectory":      [StepRecord, ...],
          "model_snapshots": [ModelSnapshot, ...]
        }
      }
    }

The hierarchy of classes mirrors this structure::

    RawSeedData
    ├── metadata:        SeedMetadata
    ├── initial_design:  InitialDesign
    └── methods:         dict[str, MethodTrajectory]
                         MethodTrajectory
                         ├── trajectory:      list[StepRecord]
                         └── model_snapshots: list[ModelSnapshot]

Design notes:
- ``train_X`` / ``train_Y`` are NEVER stored.  ``process.py`` reconstructs
  them at iteration ``t`` from ``InitialDesign + trajectory[:t]``.
- Each ``ModelSnapshot`` stores a JSON-serialised ``state_dict`` so that
  ``process.py`` can rebuild the GP via ``load_state_dict`` — never by
  re-fitting.
"""

from __future__ import annotations

import dataclasses
from typing import Any, Optional


# ---------------------------------------------------------------------------
# StepRecord  — one BO iteration
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class StepRecord:
    """One BO iteration recorded by ``run.py``.

    Attributes:
        iteration: 1-based index within the BO budget (initial design points
            are not counted; they live in :class:`InitialDesign`).
        x: Query point as ``list[float]`` (length ``dim``).
        y_obs: Noisy observation returned by ``problem.observe``.
        f_noiseless: True benchmark value; ``None`` for real-data problems.
        acq_value: Acquisition value at the selected candidate.
        train_size: Number of training points used to fit the GP *before*
            this query (i.e. ``initial_design_size + iteration - 1``).
        posterior_mean_at_candidate: GP posterior mean at ``x``, evaluated
            before the candidate was added to the training set.
        posterior_std_at_candidate: GP posterior standard deviation at ``x``.
        beta_value: UCB exploration parameter ``beta_t`` used to select this
            candidate.  ``None`` for legacy records written before the beta
            schedule was introduced (constant ``beta`` runs are unaffected:
            ``beta_t`` then equals the scalar ``beta``).
    """

    iteration: int
    x: list[float]
    y_obs: float
    f_noiseless: Optional[float]
    acq_value: float
    train_size: int
    posterior_mean_at_candidate: float
    posterior_std_at_candidate: float
    beta_value: Optional[float] = None

    @classmethod
    def from_tensors(
        cls,
        iteration: int,
        x_cand: Any,        # torch.Tensor (1, dim)
        y_obs_val: Any,     # torch.Tensor (1, 1)
        f_val: Any,         # torch.Tensor (1, 1) or None
        acq_value: Any,     # torch.Tensor scalar
        train_size: int,
        posterior_mean: float,
        posterior_std: float,
        beta_value: Optional[float] = None,
    ) -> "StepRecord":
        """Construct from raw tensors; converts everything to plain Python."""
        f: Optional[float] = f_val.squeeze().item() if f_val is not None else None
        return cls(
            iteration=iteration,
            x=x_cand.squeeze(0).tolist(),
            y_obs=y_obs_val.squeeze().item(),
            f_noiseless=f,
            acq_value=acq_value.item(),
            train_size=train_size,
            posterior_mean_at_candidate=posterior_mean,
            posterior_std_at_candidate=posterior_std,
            beta_value=(float(beta_value) if beta_value is not None else None),
        )

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "StepRecord":
        return cls(**d)


# ---------------------------------------------------------------------------
# ModelSnapshot  — lightweight per-iteration GP snapshot
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class ModelSnapshot:
    """Serialisable snapshot of a fitted GP at one BO iteration.

    Stores enough information for ``process.py`` to **reconstruct** the GP
    deterministically — without re-fitting — by:

    1. rebuilding ``train_X`` / ``train_Y`` from the initial design and
       trajectory prefix,
    2. calling :meth:`common.models.GPModelBuilder.construct` with the same
       config (``noise_std``, kernel, transforms),
    3. calling :func:`common.models.load_state_dict_into` with this
       snapshot's ``state_dict``.

    Attributes:
        iteration: 1-based BO iteration index.
        model_type: Model class name, e.g. ``"FixedNoiseGP"``.
        kernel_name: Kernel identifier, e.g. ``"matern52"``.
        noise_std: Observation noise standard deviation used at construction.
            For ``FixedNoiseGP`` this rebuilds ``train_Yvar``; for
            ``SingleTaskGP`` (learned-noise) this is ``None`` and the noise
            is recovered from the state dict.
        state_dict: JSON-serialised ``torch.nn.Module.state_dict()`` —
            sufficient to fully restore the GP via ``load_state_dict``.
        hyperparameters: Parsed scalars (``lengthscale``, ``outputscale``,
            ``noise_variance_*``, ...) for human inspection only.  Not used
            for reconstruction.
    """

    iteration: int
    model_type: str
    kernel_name: str
    noise_std: Optional[float]
    state_dict: dict[str, Any]
    hyperparameters: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "ModelSnapshot":
        return cls(**d)


# ---------------------------------------------------------------------------
# InitialDesign  — shared across all methods for one seed
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class InitialDesign:
    """Initial design points shared by every method under one seed.

    Persisted alongside the trajectory so that ``process.py`` can reconstruct
    the full evaluation history (initial design + BO steps) and the training
    inputs of every iteration without re-running BO.

    Attributes:
        X: Initial design points, shape ``(n_init, dim)``.
        y_obs: Noisy observations at ``X``, shape ``(n_init,)``.
        f_noiseless: True function values at ``X``, shape ``(n_init,)``, or
            ``None`` for real-data problems.
    """

    X: list[list[float]]
    y_obs: list[float]
    f_noiseless: Optional[list[float]]

    @classmethod
    def from_tensors(
        cls,
        X: Any,            # torch.Tensor (n_init, dim)
        y_obs: Any,        # torch.Tensor (n_init, 1)
        f_noiseless: Any,  # torch.Tensor (n_init, 1) or None
    ) -> "InitialDesign":
        return cls(
            X=X.tolist(),
            y_obs=y_obs.squeeze(-1).tolist(),
            f_noiseless=(
                f_noiseless.squeeze(-1).tolist()
                if f_noiseless is not None
                else None
            ),
        )

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "InitialDesign":
        return cls(**d)


# ---------------------------------------------------------------------------
# MethodTrajectory  — one method under one seed
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class MethodTrajectory:
    """Full BO-phase data for one method under one seed.

    Attributes:
        method_name: Identifier used as the JSON key, e.g.
            ``"right_target_matching_ucb"``.
        train_label: Description of what the GP was trained on for this
            method, e.g. ``"y_obs"`` (RIGHT) or ``"abs(y_obs - target)"``
            (WRONG).  Used by ``process.py`` to know how to reconstruct
            ``train_Y`` from the raw observations.
        trajectory: Ordered :class:`StepRecord` list (BO iterations only).
        model_snapshots: One :class:`ModelSnapshot` per BO iteration,
            captured *before* the candidate was added to the training set.
    """

    method_name: str
    train_label: str
    trajectory: list[StepRecord]
    model_snapshots: list[ModelSnapshot]

    def to_dict(self) -> dict[str, Any]:
        return {
            "train_label":     self.train_label,
            "trajectory":      [s.to_dict() for s in self.trajectory],
            "model_snapshots": [m.to_dict() for m in self.model_snapshots],
        }

    @classmethod
    def from_dict(cls, name: str, d: dict[str, Any]) -> "MethodTrajectory":
        return cls(
            method_name=name,
            train_label=d["train_label"],
            trajectory=[StepRecord.from_dict(s) for s in d["trajectory"]],
            model_snapshots=[ModelSnapshot.from_dict(m) for m in d["model_snapshots"]],
        )


# ---------------------------------------------------------------------------
# SeedMetadata
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class SeedMetadata:
    """Metadata for one (experiment, benchmark, seed) execution.

    Attributes:
        experiment: Experiment identifier, e.g. ``"exp_a_target_matching"``.
        problem_type: ``"synthetic"`` or ``"real_data"``.
        benchmark: Problem name, e.g. ``"sine_trend_1d"``.
        seed: Random seed used for the Sobol design and BO trajectory.
        budget: Number of BO iterations (excluding the initial design).
        initial_design_size: Number of Sobol initial design points.
        target: Target value ``T`` for the target-matching objective.
        noise_std: Observation noise standard deviation.
        dim: Input dimension.
        bounds: Box bounds, ``[[lb_1, ..., lb_d], [ub_1, ..., ub_d]]``.
        beta: Representative UCB exploration parameter (``beta_t`` at ``t = 1``
            for a schedule; the constant value otherwise).  ``None`` for
            legacy metadata.
        beta_schedule: Config-shaped ``BetaSchedule`` dict actually used
            (``{"type", ...}``), or ``None`` for a plain constant / legacy run.
    """

    experiment: str
    problem_type: str
    benchmark: str
    seed: int
    budget: int
    initial_design_size: int
    target: float
    noise_std: float
    dim: int
    bounds: Optional[list[list[float]]] = None
    beta: Optional[float] = None
    beta_schedule: Optional[dict[str, Any]] = None

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "SeedMetadata":
        # Filter unknown keys so the loader is tolerant of newer fields when
        # an older codebase reads recent results, and vice-versa.
        known = {f.name for f in dataclasses.fields(cls)}
        return cls(**{k: v for k, v in d.items() if k in known})


# ---------------------------------------------------------------------------
# RawSeedData  — top-level
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class RawSeedData:
    """All raw data for one (experiment, benchmark, seed) triple.

    Attributes:
        metadata: Run-level metadata.
        initial_design: Sobol initial design shared by every method.
        methods: Per-method trajectories, keyed by method name.
    """

    metadata:        SeedMetadata
    initial_design:  InitialDesign
    methods:         dict[str, MethodTrajectory]

    def to_dict(self) -> dict[str, Any]:
        return {
            "metadata":       self.metadata.to_dict(),
            "initial_design": self.initial_design.to_dict(),
            "methods":        {name: m.to_dict() for name, m in self.methods.items()},
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "RawSeedData":
        return cls(
            metadata=SeedMetadata.from_dict(d["metadata"]),
            initial_design=InitialDesign.from_dict(d["initial_design"]),
            methods={
                name: MethodTrajectory.from_dict(name, md)
                for name, md in d.get("methods", {}).items()
            },
        )
